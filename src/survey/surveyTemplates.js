// ---- سازنده‌های سؤال (idها داخلِ هر الگو یکتا هستند) ----
function maker(prefix) {
  let n = 0;
  const O = (labels) => labels.map((label, i) => ({ id: `o${i + 1}`, label }));
  return {
    section: (title, description = "") => ({ id: `${prefix}_s${(n += 1)}`, type: "section", title, description, required: false, config: {} }),
    text: (title, long = false, required = true) => ({ id: `${prefix}_q${(n += 1)}`, type: long ? "long_text" : "short_text", title, description: "", required, config: {} }),
    single: (title, labels, correctIdx = null, points = 1) => ({
      id: `${prefix}_q${(n += 1)}`, type: "single_choice", title, description: "", required: true,
      config: { options: O(labels), points, correct: correctIdx == null ? [] : [`o${correctIdx + 1}`] },
    }),
    multi: (title, labels, correctIdxs = [], points = 1) => ({
      id: `${prefix}_q${(n += 1)}`, type: "multi_choice", title, description: "", required: true,
      config: { options: O(labels), points, correct: correctIdxs.map((i) => `o${i + 1}`) },
    }),
    yesno: (title, correct = null, points = 1) => ({
      id: `${prefix}_q${(n += 1)}`, type: "yes_no", title, description: "", required: true,
      config: { points, correct: correct ? [correct] : [] },
    }),
    rating: (title, required = true) => ({ id: `${prefix}_q${(n += 1)}`, type: "rating", title, description: "", required, config: { max: 5 } }),
    scale: (title, minLabel, maxLabel, required = true) => ({ id: `${prefix}_q${(n += 1)}`, type: "linear_scale", title, description: "", required, config: { min: 1, max: 5, step: 1, minLabel, maxLabel } }),
  };
}

